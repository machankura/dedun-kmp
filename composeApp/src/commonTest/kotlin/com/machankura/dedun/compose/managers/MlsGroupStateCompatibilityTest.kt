package com.machankura.dedun.compose.managers

import com.vitorpamplona.marmot.groups.MarmotGroupPolicy
import com.vitorpamplona.marmot.groups.currentGroupState
import com.vitorpamplona.marmot.groups.currentMarmotData
import com.vitorpamplona.mls.codec.TlsReader
import com.vitorpamplona.mls.codec.TlsWriter
import com.vitorpamplona.mls.group.MlsGroup
import com.vitorpamplona.mls.group.MlsGroupState
import com.vitorpamplona.mls.group.RetainedEpochSecrets
import com.vitorpamplona.quartz.nip01Core.core.hexToByteArray
import kotlin.test.Test
import kotlin.test.assertContentEquals
import kotlin.test.assertEquals
import kotlin.test.assertNotNull
import kotlin.test.assertTrue
import com.machankura.dedun.compose.extensions.exporterSecret

/**
 * A group state blob written by the engine the app shipped before this move still opens.
 *
 * This is the constraint the whole of docs/marmot-kmp.md hangs on. `ChatRoom.mlsGroupState`
 * is a `MlsGroupState.encodeTls()` blob, written by quartz 1.15.2's MLS engine on every
 * device that has ever been in a group. If mls-kmp cannot read one, an upgrade costs every
 * user every room they are in, and the only repair is a new group and a re-invite -- there
 * is no in-place migration from a legacy group, which marmot-kmp's own
 * `LegacyGroupContractTest` says in as many words.
 *
 * The argument that it holds is good: the blob's first field is a `uint16` version,
 * quartz 1.15.2 wrote `STATE_VERSION = 4`, mls-kmp 1.3.0 accepts `1..10`, and its comments
 * say each version only appends. But an argument is not a measurement, and [OldEngineBlob]
 * is the measurement: real bytes from the old engine, generated by a throwaway project
 * with `com.vitorpamplona.quartz:quartz:1.15.2` as its only dependency, pinned so that
 * the day a future mls-kmp stops reading version 4, this test says so rather than a
 * user's phone.
 *
 * This is the blob on its own. `ShippedProfileUpgradeJvmTest` is the same bytes in a
 * database at the version the app shipped, opened by this branch -- the other half of
 * the same constraint. docs/marmot-kmp.md, Phases 4 and 9.
 */
class MlsGroupStateCompatibilityTest {

    /**
     * The first two bytes are the state version. Asserted on its own, because a fixture
     * that quietly became a version-10 blob would make every assertion below pass while
     * testing nothing.
     */
    @Test
    fun `the fixture is a blob the old engine wrote, at its state version`() {
        val bytes = OldEngineBlob.HEX.hexToByteArray()
        assertEquals(
            OldEngineBlob.STATE_VERSION,
            OldEngineBlob.stateVersionOf(bytes),
            "the fixture is no longer a blob quartz 1.15.2 would have written",
        )
    }

    /** It decodes, and it still says what it said. */
    @Test
    fun `mls-kmp decodes it and keeps what it said`() {
        val state = MlsGroupState.decodeTls(OldEngineBlob.HEX.hexToByteArray())

        assertEquals(0L, state.groupContext.epoch, "epoch moved in the decode")
        assertEquals(0, state.myLeafIndex, "the creator is no longer leaf 0")
        assertEquals(32, state.groupContext.groupId.size, "the MLS group id lost its shape")
        assertTrue(state.encryptionSecret.isNotEmpty(), "no encryption secret came back")
    }

    /**
     * And the group rebuilds from it: the key schedule, the secret tree and the ratchet
     * tree, under Marmot's policy, with its MIP-01 metadata where the app reads it.
     */
    @Test
    fun `the group restores from it with its metadata intact`() {
        val group = MlsGroup.restore(MlsGroupState.decodeTls(OldEngineBlob.HEX.hexToByteArray()), MarmotGroupPolicy)

        assertTrue(group.isLocalMember(), "the restored group does not hold us")
        val data = assertNotNull(group.currentMarmotData(), "the 0xF2EE extension did not survive")
        assertEquals(OldEngineBlob.ROOM_ID, data.nostrGroupId, "the room's address changed")
        assertEquals("Fixture", data.name, "the group's name changed")
        assertTrue(group.currentGroupState().isCurrentProfile.not(), "a legacy group read as current-profile")
    }

    /**
     * The kind:445 key the app seals a group event with, from a group restored out of an
     * old blob. 32 bytes or `GroupEventEncryption` refuses it -- which is how Phase 1
     * found that a group restored without [MarmotGroupPolicy] is not a Marmot group, so
     * this is that fix pinned against real pre-migration bytes rather than a fixture
     * built by the new engine.
     */
    @Test
    fun `the outer kind445 key is derivable from a restored old group`() {
        val group = MlsGroup.restore(MlsGroupState.decodeTls(OldEngineBlob.HEX.hexToByteArray()), MarmotGroupPolicy)

        assertEquals(32, group.exporterSecret().size, "the group-event exporter secret is the wrong length")
    }

    /**
     * Re-saved, it comes back at the current state version and still decodes -- the
     * upgrade path for a room, which happens the first time the manager persists it.
     */
    @Test
    fun `a re-save moves it to the current version and still decodes`() {
        val group = MlsGroup.restore(MlsGroupState.decodeTls(OldEngineBlob.HEX.hexToByteArray()), MarmotGroupPolicy)

        val resaved = group.saveState().encodeTls()
        val version = OldEngineBlob.stateVersionOf(resaved)
        assertTrue(
            version > OldEngineBlob.STATE_VERSION,
            "a re-save did not move the blob forward: version $version",
        )

        val again = MlsGroupState.decodeTls(resaved)
        assertEquals(0L, again.groupContext.epoch)
        assertEquals(0, again.myLeafIndex)
        assertContentEquals(
            MlsGroupState.decodeTls(OldEngineBlob.HEX.hexToByteArray()).groupContext.groupId,
            again.groupContext.groupId,
            "the group id changed across a re-save",
        )
    }

    /**
     * The version a save is written at today, exactly. The test above only says "newer
     * than the old engine's", which a library that moved to 11 would still pass. But a
     * bump changes what every device writes on its next save, and a build older than
     * that library cannot read the result back -- so a downgrade, or a peer device on an
     * older build sharing a backup, loses the room. When this fails, read the library's
     * upgrading guide for what the new version appends and whether `decodeTls` still
     * takes 4, and only then move the number. docs/quartz-mls-marmot-update.md, Phase 4.
     */
    @Test
    fun `a save is written at the state version this app was checked against`() {
        val group = MlsGroup.restore(MlsGroupState.decodeTls(OldEngineBlob.HEX.hexToByteArray()), MarmotGroupPolicy)

        assertEquals(
            CHECKED_STATE_VERSION,
            OldEngineBlob.stateVersionOf(group.saveState().encodeTls()),
            "mls-kmp writes a new state version -- check what it appends before moving this",
        )
    }

    /**
     * The retained-epoch window is the app's own rows, not an opaque blob:
     * `RoomMlsGroupStateStore` decodes each one into five columns and re-encodes it from
     * them. A sixth field in `RetainedEpochSecrets` would be silently truncated on every
     * load, so the five are pinned here by round-tripping them.
     */
    @Test
    fun `the retained epoch record still has the five fields the app stores`() {
        val retained = RetainedEpochSecrets(
            epoch = 7L,
            senderDataSecret = ByteArray(32) { 1 },
            encryptionSecret = ByteArray(32) { 2 },
            leafCount = 3,
            exporterSecret = ByteArray(32) { 4 },
        )

        val writer = TlsWriter()
        retained.encodeTls(writer)
        val back = RetainedEpochSecrets.decodeTls(TlsReader(writer.toByteArray()))

        assertEquals(7L, back.epoch)
        assertContentEquals(retained.senderDataSecret, back.senderDataSecret)
        assertContentEquals(retained.encryptionSecret, back.encryptionSecret)
        assertEquals(3, back.leafCount)
        assertContentEquals(retained.exporterSecret, back.exporterSecret)
    }

    private companion object {
        /** mls-kmp 1.3.0 and 1.3.1 both write 10. */
        const val CHECKED_STATE_VERSION = 10
    }
}
